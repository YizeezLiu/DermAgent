"""
Case-level execution for dermatology benchmarks (Task 1-3).

Loads a plan.json generated by Derm_Task_level.py, then for each sample in
the CSV dataset:
  1. Runs quantitative steps (PanDerm, MAKE, RAG via bridge tools).
  2. Runs qualitative steps (GPT-4o VLM analysis via GPT_Decider).
  3. Summarises qualitative results (Summary_Module).
  4. Produces a final decision (task-specific Decider).

Usage:
    # Task 1: Zero-shot classification (HAM10000)
    python Derm_Case_level.py --task 1 \\
        --csv-path ../../datasets/ham10000/HAM10000_benchmark_500.csv \\
        --image-dir ../../datasets/ham10000 \\
        --max-samples 500

    # Task 2: Concept annotation (Derm7pt-100)
    python Derm_Case_level.py --task 2 \\
        --csv-path ../../datasets/derm7pt/meta_task2_sample_100.csv \\
        --image-dir ../../datasets/derm7pt/final_images \\
        --max-samples 100

    # Task 3: Image captioning (SkinCAP-100)
    python Derm_Case_level.py --task 3 \\
        --csv-path ../../datasets/skin_cap/skin_cap_meta_100.csv \\
        --image-dir ../../datasets/skin_cap \\
        --max-samples 100
"""

