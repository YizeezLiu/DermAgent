def final_decision_task1(plan, save_dir, task, image_path, decider):
    """Multi-class classification → pick one of HAM10000_CLASSES."""
    indicators = _collect_indicators(plan, save_dir)
    input_desc = str(task.get("input", ""))
    disease_goal = str(task.get("disease", ""))

    prompt = (
        f"You are a clinical decision assistant for dermatology.\n"
        f"Input: {input_desc}\n"
        f"Goal: {disease_goal}\n"
    )
    decider.decide(
        output_file=os.path.join(save_dir, "final_diagnosis.json"),
        prompt=prompt,
        indicators=indicators,
        candidate_classes=HAM10000_CLASSES,
        image_paths=[image_path],
        field="overall",
    )


def final_decision_task2(plan, save_dir):
    """Concept annotation — collect per-concept Yes/No from brief_diagnosis.json."""
    brief_path = os.path.join(save_dir, "brief_diagnosis.json")
    if not os.path.exists(brief_path):
        return

    with open(brief_path, "r", encoding="utf-8") as f:
        brief = json.load(f)

    concepts_result = {}
    for step in plan:
        if str(step.get("output_type", "")).lower() != "final indicator":
            continue
        action = step.get("action", "").lower()
        step_field = f"step_{step.get('id')}"
        answer = str(brief.get(step_field, "")).strip().lower()
        is_present = "yes" in answer
        concepts_result[step.get("action", "")] = {
            "present": is_present,
            "raw_answer": brief.get(step_field, ""),
        }

    out_path = os.path.join(save_dir, "final_diagnosis.json")
    result = {"overall": {"concepts": concepts_result}}
    with open(out_path, "w", encoding="utf-8") as f:
        json.dump(result, f, indent=4, ensure_ascii=False)


def final_decision_task3(plan, save_dir):
    """Captioning — extract the last qualitative VLM step's output as caption."""
    diag_path = os.path.join(save_dir, "diagnosis.json")
    if not os.path.exists(diag_path):
        return

    with open(diag_path, "r", encoding="utf-8") as f:
        diag = json.load(f)

    # Find the last qualitative step (highest id with action_type=qualitative)
    last_qual = None
    for step in reversed(plan):
        if str(step.get("action_type", "")).lower() == "qualitative":
            last_qual = step
            break

    caption = ""
    if last_qual:
        step_field = f"step_{last_qual.get('id')}"
        caption = str(diag.get(step_field, "")).strip()

    if not caption:
        # Fallback: take the last available step output
        for key in sorted(diag.keys(), reverse=True):
            if diag[key]:
                caption = str(diag[key]).strip()
                break

    out_path = os.path.join(save_dir, "final_diagnosis.json")
    result = {"overall": {"caption": caption}}
    with open(out_path, "w", encoding="utf-8") as f:
        json.dump(result, f, indent=4, ensure_ascii=False)


def _collect_indicators(plan, save_dir):
    """Gather indicator evidence from brief_diagnosis.json for Pro/MultiClass_Decider."""
    brief_path = os.path.join(save_dir, "brief_diagnosis.json")
    if os.path.exists(brief_path):
        with open(brief_path, "r", encoding="utf-8") as f:
            brief = json.load(f)
    else:
        brief = {}

    diag_path = os.path.join(save_dir, "diagnosis.json")
    if os.path.exists(diag_path):
        with open(diag_path, "r", encoding="utf-8") as f:
            diag = json.load(f)
    else:
        diag = {}

    indicators = []
    for step in plan:
        step_field = f"step_{step.get('id')}"
        at = str(step.get("action_type", "")).lower()
        ot = str(step.get("output_type", "")).lower()

        evidence = brief.get(step_field, diag.get(step_field, ""))
        if isinstance(evidence, (dict, list)):
            evidence = json.dumps(evidence, ensure_ascii=False)[:500]

        indicators.append({
            "indicator_name": step.get("action", f"step_{step.get('id')}"),
            "evidence": str(evidence),
            "action_type": at,
            "output_type": ot,
        })
    return indicators


