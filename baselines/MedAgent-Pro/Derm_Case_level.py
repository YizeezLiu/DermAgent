def run_plan_for_sample(
    plan: list,
    plan_by_id: dict,
    tool_by_id: dict,
    tool_registry: dict,
    image_path: str,
    save_dir: str,
    task: dict,
    analyzer: GPT_Decider,
    summarizer: Summary_Module,
    task_id: int,
):
    """Execute all plan steps for a single sample."""
    for step in plan:
        at = str(step.get("action_type", "")).lower()
        tool_ids = step.get("tool", []) or []
        if not isinstance(tool_ids, list):
            tool_ids = [tool_ids]
        save_name = step.get("output_path", "diagnosis.json")

        if at == "quantitative":
            _run_quantitative(
                step, tool_ids, tool_by_id, tool_registry, plan_by_id,
                image_path, save_dir, save_name, task
            )
        elif at == "qualitative":
            _run_qualitative(
                step, plan_by_id, image_path, save_dir, save_name,
                analyzer, summarizer, task_id
            )


def _run_quantitative(step, tool_ids, tool_by_id, tool_registry, plan_by_id,
                       image_path, save_dir, save_name, task):
    for tid in tool_ids:
        tool_def = tool_by_id.get(int(tid))
        if tool_def is None:
            print(f"  [warn] tool id {tid} not in toolset")
            continue

        if "coding" in str(tool_def.get("type", "")).lower():
            fn_name = (
                f"{snake(step.get('action') or step.get('output_type') or 'generated_fn')}"
                f"_{int(step.get('id', 0))}"
            )
        else:
            fn_name = command_to_fn_name(tool_def.get("command", ""))

        fn = tool_registry.get(fn_name)
        if fn is None:
            print(f"  [warn] function '{fn_name}' not registered")
            continue

        deps = step.get("input_type", []) or []
        resolved = []
        for dep in deps:
            dep = int(dep)
            if dep == 0:
                resolved.append(image_path)
            else:
                prev = plan_by_id.get(dep)
                if prev:
                    resolved.append(os.path.join(save_dir, prev.get("output_path", "")))

        try:
            if "coding" in str(tool_def.get("type", "")).lower():
                fn(resolved, save_dir, save_name)
            else:
                primary = resolved[0] if resolved else image_path
                fn(primary, save_dir, save_name)
        except Exception as e:
            print(f"  [error] '{fn_name}': {e}")


def _run_qualitative(step, plan_by_id, image_path, save_dir, save_name,
                      analyzer, summarizer, task_id):
    try:
        image_input, text_input = [], []
        for dep in step.get("input_type", []) or []:
            dep = int(dep)
            if dep == 0:
                image_input.append(image_path)
            else:
                prev_step = plan_by_id.get(dep, {})
                prev_save_name = prev_step.get("output_path", "")
                t, img = read_prev_output(save_dir, prev_save_name, dep)
                if img:
                    image_input.append(img)
                if t:
                    text_input.append(t)

        ques = step.get("action", "")
        full_prompt = build_qual_prompt(ques, text_input)
        step_field = f"step_{step.get('id')}"

        analyzer.decide(
            output_file=os.path.join(save_dir, save_name),
            prompt=full_prompt,
            image_paths=image_input,
            field=step_field,
        )

        # Summary prompt adapts per task
        if task_id == 1:
            summary_prompt = (
                f"Based on the above analysis, what is the most likely diagnosis? "
                f"The task is: {ques}. "
                f"Answer with ONLY the disease name from: {', '.join(HAM10000_CLASSES)}"
            )
        elif task_id == 2:
            summary_prompt = (
                f"Based on the above text, does this image show the described feature? "
                f"The task is: {ques}. Answer with only one word (Yes or No)"
            )
        else:  # task 3 — no summary, raw VLM output is the caption
            return

        summarizer.summarize(
            input_file=os.path.join(save_dir, save_name),
            output_file=os.path.join(save_dir, "brief_diagnosis.json"),
            prompt=summary_prompt,
            field=step_field,
        )
    except Exception as e:
        print(f"  [error] qualitative step {step.get('id')}: {e}")


