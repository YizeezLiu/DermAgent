def main():
    args = parse_args()
    task_id = args.task
    defaults = TASK_DEFAULTS[task_id]
    data_root = defaults["data_root"]

    image_col = args.image_col or defaults["image_col"]
    image_dir = args.image_dir

    # Load task + plan + toolset
    with open(os.path.join(data_root, "task.json"), "r") as f:
        task = json.load(f)
    plan_path = os.path.join(data_root, "plan.json")
    if not os.path.exists(plan_path):
        print(f"[ERROR] {plan_path} not found. Run Derm_Task_level.py first.")
        sys.exit(1)
    with open(plan_path, "r") as f:
        plan = json.load(f)
    with open(os.path.join(data_root, "toolset.json"), "r") as f:
        toolset = json.load(f)

    tool_by_id = {int(t["id"]): t for t in toolset if "id" in t}
    plan_by_id = {int(s["id"]): s for s in plan if "id" in s}

    # Tool function registry
    TOOL_FN_REGISTRY = {
        "panderm_classify": panderm_classify,
        "make_annotate": make_annotate,
        "rag_retrieve": rag_retrieve,
    }

    # Code generation for coding steps
    ensure_pkg_inited(data_root)
    coder = Coding_Agent(OPENAI_API_KEY)
    code_path = os.path.join(data_root, "tools", "GenCode.py")
    os.makedirs(os.path.dirname(code_path), exist_ok=True)
    if not os.path.exists(code_path):
        with open(code_path, "w", encoding="utf-8") as f:
            f.write("# Generated code\n")

    for step in plan:
        step_tool_ids = step.get("tool", []) or []
        if not isinstance(step_tool_ids, list):
            step_tool_ids = [step_tool_ids]
        is_coding = any(
            "coding" in str(tool_by_id.get(int(tid), {}).get("type", "")).lower()
            for tid in step_tool_ids
        )
        if not is_coding:
            continue

        fn_name, requirement = _build_requirement(step, plan_by_id, tool_by_id, task)
        try:
            coder.generate_function(
                output_file=code_path,
                requirement=requirement,
                enforce_function_name=fn_name,
                extra_context=(
                    "`inputs` is a list; each item may be a file path or an "
                    "in-memory object. Handle both gracefully."
                ),
                model="chatgpt-4o-latest",
            )
            register_generated_function(data_root, TOOL_FN_REGISTRY, fn_name)
        except Exception as e:
            print(f"[warn] CodingAgent failed for step {step.get('id')}: {e}")

    # LLM modules
    analyzer = GPT_Decider(OPENAI_API_KEY)
    summarizer = Summary_Module(OPENAI_API_KEY)
    mc_decider = MultiClass_Decider(OPENAI_API_KEY) if task_id == 1 else None

    # Load dataset
    df = pd.read_csv(args.csv_path)
    if args.max_samples:
        df = df.head(args.max_samples)

    # Output directory
    tag = args.output_tag or datetime.now().strftime("%Y%m%d_%H%M%S")
    record_root = os.path.join(data_root, "record", tag)
    os.makedirs(record_root, exist_ok=True)

    # Save run config
    run_config = {
        "task": task_id,
        "csv_path": args.csv_path,
        "image_dir": image_dir,
        "num_samples": len(df),
        "timestamp": tag,
        "plan_steps": len(plan),
    }
    with open(os.path.join(record_root, "run_config.json"), "w") as f:
        json.dump(run_config, f, indent=2)

    print(f"\nTask {task_id} | {len(df)} samples | {len(plan)} plan steps")
    print(f"Output: {record_root}\n")

    # Main execution loop
    results = []
    for idx, row in tqdm(df.iterrows(), total=len(df), desc=f"Task {task_id}"):
        img_file = str(row[image_col])
        image_path = os.path.join(image_dir, img_file)
        if not os.path.exists(image_path):
            print(f"  [skip] image not found: {image_path}")
            continue

        sample_id = Path(img_file).stem
        save_dir = os.path.join(record_root, sample_id)

        # Resume: skip already-completed samples
        if args.resume and os.path.exists(os.path.join(save_dir, "final_diagnosis.json")):
            continue

        os.makedirs(save_dir, exist_ok=True)

        t0 = time.time()
        try:
            # Run all plan steps
            run_plan_for_sample(
                plan, plan_by_id, tool_by_id, TOOL_FN_REGISTRY,
                image_path, save_dir, task, analyzer, summarizer, task_id
            )

            # Final decision (task-specific)
            if task_id == 1:
                final_decision_task1(plan, save_dir, task, image_path, mc_decider)
            elif task_id == 2:
                final_decision_task2(plan, save_dir)
            elif task_id == 3:
                final_decision_task3(plan, save_dir)

            elapsed = time.time() - t0
            results.append({"sample": sample_id, "status": "ok", "time": elapsed})

        except Exception as e:
            elapsed = time.time() - t0
            print(f"  [FAIL] {sample_id}: {e}")
            traceback.print_exc()
            results.append({"sample": sample_id, "status": "error", "error": str(e),
                            "time": elapsed})

    # Save execution summary
    summary_path = os.path.join(record_root, "execution_summary.json")
    ok = sum(1 for r in results if r["status"] == "ok")
    err = sum(1 for r in results if r["status"] == "error")
    with open(summary_path, "w") as f:
        json.dump({
            "total": len(results), "ok": ok, "error": err,
            "results": results,
        }, f, indent=2)

    print(f"\nDone: {ok}/{len(results)} succeeded, {err} errors")
    print(f"Results: {record_root}")
    print(f"Next: python Derm_Evaluator.py --task {task_id} --record-dir {record_root} "
          f"--csv-path {args.csv_path}")


def _build_requirement(step, plan_by_id, tool_by_id, task):
    """Build (function_name, requirement_text) for Coding_Agent."""
    base = step.get("action") or step.get("output_type") or "generated_fn"
    fn_name = f"{snake(base)}_{int(step.get('id', 0))}"
    in_desc_list = inputs_desc(step, plan_by_id, tool_by_id, task.get("input", ""))
    in_desc_str = ", ".join(in_desc_list)
    out_desc = str(step.get("output_type", "")).strip()
    step_id = int(step.get("id", 0))

    requirement = (
        "Implement a Python function with the EXACT signature:\n"
        f"{fn_name}(inputs, save_dir, save_name)\n\n"
        "Semantics:\n"
        "- `inputs` is a LIST; elements correspond IN ORDER to step dependencies.\n"
        f"- Conceptual inputs: {in_desc_str}\n"
        f"- Output (conceptual): {out_desc}\n\n"
        "Constraints:\n"
        "- Self-contained (import inside if needed). No print statements.\n"
        "- Always use `os.path.join(save_dir, save_name)` as the output path for non-image results.\n"
        "- When writing non-image results, read existing JSON if present, "
        f"update key 'step_{step_id}', write back with ensure_ascii=False.\n"
        "- Add a brief docstring.\n"
    )
    return fn_name, requirement


if __name__ == "__main__":
    main()
